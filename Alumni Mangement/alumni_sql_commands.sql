/*
1.Alumni Directory
The college admin wants to view a list of all alumni with:
Full Name
Department Name
Batch
Location
Sort the list by batch (latest first) and then by first name.
*/
SELECT CONCAT(A.FIRST_NAME,' ',A.LAST_NAME) AS FULL_NAME,D.DEPT_NAME,A.BATCH,A.LOCATION FROM ALUMNI A INNER JOIN DEPARTMENT D ON A.DEPT_ID=D.DEPT_ID ORDER BY A.BATCH,A.FIRST_NAME;

/*
2.PLACEMENT REPORT
The placement officer wants to know:
How many alumni are working in each company?
Display:
Company Name
Total Alumni Working
Arrange from highest to lowest.
*/
SELECT C.COMPANY_NAME,COUNT(E.ALUMNI_ID) FROM company C JOIN employment E ON C.COMPANY_ID=E.COMPANY_ID GROUP BY COMPANY_NAME ORDER BY COUNT(E.ALUMNI_ID) DESC;

/*
3.Event Participation
Requirement:
The event coordinator wants a report showing:
Event Name
Number of alumni registered
Include all events.
*/
SELECT E.EVENT_NAME,COUNT(ER.ALUMNI_ID) FROM EVENT E LEFT JOIN EVENT_REGISTRATION ER ON E.EVENT_ID=ER.EVENT_ID GROUP BY EVENT_NAME;

/*
4. Skill Search
A recruiter is looking for alumni who have the Java skill.
Display:
Alumni Name
Skill Name
Department
*/
SELECT CONCAT(A.FIRST_NAME,' ',A.LAST_NAME) AS ALUMNI_NAME,S.SKILL_NAME,D.DEPT_NAME FROM ALUMNI A LEFT JOIN DEPARTMENT D ON D.DEPT_ID=A.DEPT_ID LEFT JOIN ALUMNI_SKILLS SA ON A.ALUMNI_ID=SA.ALUMNI_ID LEFT JOIN SKILL S ON SA.SKILL_ID=S.SKILL_ID WHERE S.SKILL_NAME="JAVA";

/*
5.FEEDBACK ANALYSIS
The principal wants to know:
Which events received an average rating of 4 or above?
Display:
Event Name
Average Rating
*/
SELECT E.EVENT_NAME,AVG(F.RATING) FROM EVENT E LEFT JOIN FEEDBACK F ON E.EVENT_ID=F.EVENT_ID GROUP BY E.EVENT_NAME HAVING AVG(F.RATING)>=4;

