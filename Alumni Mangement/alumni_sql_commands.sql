/*
SCENARIO 16:
Prevent invalid feedback rating
*/

DELIMITER //
CREATE TRIGGER TRG_CHECK_RATING
BEFORE INSERT
ON FEEDBACK
FOR EACH ROW
BEGIN
IF NEW.RATING < 1 OR NEW.RATING > 5 THEN
SIGNAL SQLSTATE '45000'
SET MESSAGE_TEXT='Rating must be between 1 and 5';
END IF;
END//
DELIMITER ;

